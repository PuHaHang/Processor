"""
데이터 타입 정의 모듈

이 모듈은 프로세서 파이프라인에서 사용되는 데이터 타입들을 정의합니다.
"""

from enum import Enum


class DataType (Enum):
    """
    처리 데이터의 타입을 정의하는 열거형
    
    프로세서 파이프라인에서 처리되는 데이터의 타입을 나타냅니다.
    각 프로세서는 특정 데이터 타입을 입력으로 받아 다른 타입으로 변환합니다.
    """
    URL = 0     # URL 문자열 데이터
    VIDEO = 1   # 비디오 바이너리 데이터
    AUDIO = 2   # 오디오 바이너리 데이터
    TEXT = 3    # 텍스트 문자열 데이터
    METADATA = 4 # 메타데이터 데이터